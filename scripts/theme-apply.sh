#!/bin/bash
# theme-apply.sh — Apply the active theme from themes.toml to all apps.
#
# Called automatically by DWM on config reload (SIGUSR1 / file save).
# Can also be run manually: theme-apply.sh
#
# Updates: alacritty · ghostty · quickshell

set -euo pipefail

# ── Concurrency Lock ───────────────────────────────────────────────────────────
LOCK_FILE="${XDG_RUNTIME_DIR:-/tmp}/theme-apply.lock"
exec 200>"$LOCK_FILE"
if ! flock -n 200; then
    flock -w 3 200 || exit 0
fi

THEMES_FILE="${THEMES_FILE:-${XDG_CONFIG_HOME:-$HOME/.config}/dwm/themes.toml}"

# ── Skip integration writes if dwm-settings-theme transaction is pending ──────
STATE_HOME="${XDG_STATE_HOME:-$HOME/.local/state}"
TX_FILE="$STATE_HOME/dwm/appearance/integration-transaction"
SUPPRESS_FILE="$STATE_HOME/dwm/appearance/integration-suppress"
if [[ -f "$TX_FILE" ]]; then
    read -r _tx_hash _tx_state < "$TX_FILE" 2>/dev/null || true
    if [[ "${_tx_state:-}" == "pending" ]]; then
        # An atomic transaction is currently preparing its own staged integration outputs
        exit 0
    fi
fi
if [[ -f "$THEMES_FILE" && -f "$SUPPRESS_FILE" ]]; then
    _curr_hash=$(sha256sum "$THEMES_FILE" | awk '{print $1}')
    _suppress_hash=$(cat "$SUPPRESS_FILE" 2>/dev/null || true)
    if [[ "$_curr_hash" == "$_suppress_hash" ]]; then
        exit 0
    fi
fi
if [[ ! -f "$THEMES_FILE" ]]; then
    SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
    if [[ -n "${DWM_DATA_DIR:-}" && -f "$DWM_DATA_DIR/config/themes.toml" ]]; then
        THEMES_FILE="$DWM_DATA_DIR/config/themes.toml"
    elif [[ -f "${XDG_DATA_HOME:-$HOME/.local/share}/dwm/config/themes.toml" ]]; then
        THEMES_FILE="${XDG_DATA_HOME:-$HOME/.local/share}/dwm/config/themes.toml"
    elif [[ -f "$SCRIPT_DIR/../config/themes.toml" ]]; then
        THEMES_FILE="$SCRIPT_DIR/../config/themes.toml"
    else
        echo "theme-apply: themes.toml not found at $THEMES_FILE" >&2
        exit 1
    fi
fi

# ── Minimal TOML section reader ───────────────────────────────────────────────
# toml_get SECTION KEY FILE — prints the value or empty string
toml_get() {
    local section="$1" key="$2" file="$3"
    awk -v sec="[$section]" -v key="$key" '
        /^\[/ { in_sec = ($0 == sec) }
        in_sec && $0 ~ "^[[:space:]]*" key "[[:space:]]*=" {
            sub(/^[^=]*=[[:space:]]*/, "")
            gsub(/"/, "")
            gsub(/[[:space:]]+#.*$/, "")  # strip inline comments (not # in hex colors)
            sub(/[[:space:]]+$/, "")
            print; exit
        }
    ' "$file"
}

# ── Read active theme name ────────────────────────────────────────────────────
THEME_NAME="$(toml_get "active" "theme" "$THEMES_FILE")"
if [[ -z "$THEME_NAME" ]]; then
    echo "theme-apply: no [active] theme set in $THEMES_FILE" >&2
    exit 1
fi

SECTION="theme.$THEME_NAME"

# ── Helper: read a value from the active theme section ───────────────────────
theme_get() {
    toml_get "$SECTION" "$1" "$THEMES_FILE"
}

# ── Read all theme values ─────────────────────────────────────────────────────
TERM_BG="$(theme_get term_bg)"
TERM_FG="$(theme_get term_fg)"
TERM_CURSOR="$(theme_get term_cursor)"
TERM_C0="$(theme_get term_color0)"
TERM_C1="$(theme_get term_color1)"
TERM_C2="$(theme_get term_color2)"
TERM_C3="$(theme_get term_color3)"
TERM_C4="$(theme_get term_color4)"
TERM_C5="$(theme_get term_color5)"
TERM_C6="$(theme_get term_color6)"
TERM_C7="$(theme_get term_color7)"
TERM_C8="$(theme_get term_color8)"
TERM_C9="$(theme_get term_color9)"
TERM_C10="$(theme_get term_color10)"
TERM_C11="$(theme_get term_color11)"
TERM_C12="$(theme_get term_color12)"
TERM_C13="$(theme_get term_color13)"
TERM_C14="$(theme_get term_color14)"
TERM_C15="$(theme_get term_color15)"

GHOSTTY_THEME="$(theme_get ghostty_theme)"
ROFI_THEME="$(theme_get rofi_theme)"

DARK_MODE="$(theme_get dark_mode)"
[[ "$DARK_MODE" != "false" ]] && DARK_MODE="true"  # default to dark if unset

NORM_BG="$(theme_get normbgcolor)"
NORM_FG="$(theme_get normfgcolor)"
NORM_BORDER="$(theme_get normbordercolor)"
SEL_BG="$(theme_get selbgcolor)"
SEL_FG="$(theme_get selfgcolor)"
SEL_BORDER="$(theme_get selbordercolor)"

[[ -z "$NORM_BG" ]] && NORM_BG="$TERM_BG"
[[ -z "$NORM_FG" ]] && NORM_FG="$TERM_FG"
[[ -z "$NORM_BORDER" ]] && NORM_BORDER="$TERM_C8"
[[ -z "$SEL_BG" ]] && SEL_BG="$TERM_C0"
[[ -z "$SEL_FG" ]] && SEL_FG="$TERM_FG"
[[ -z "$SEL_BORDER" ]] && SEL_BORDER="$TERM_CURSOR"


# ══════════════════════════════════════════════════════════════════════════════
# ALACRITTY — write ~/.config/alacritty/active-theme.toml
# ══════════════════════════════════════════════════════════════════════════════
ALACRITTY_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/alacritty"
if [[ -d "$ALACRITTY_DIR" ]]; then
    cat > "$ALACRITTY_DIR/active-theme.toml" <<EOF
# Auto-generated by theme-apply.sh — do not edit manually.
# Change the theme in ~/.config/dwm/themes.toml instead.

[colors.primary]
background = '$TERM_BG'
foreground = '$TERM_FG'

[colors.cursor]
text   = '$TERM_BG'
cursor = '$TERM_CURSOR'

[colors.normal]
black   = '$TERM_C0'
red     = '$TERM_C1'
green   = '$TERM_C2'
yellow  = '$TERM_C3'
blue    = '$TERM_C4'
magenta = '$TERM_C5'
cyan    = '$TERM_C6'
white   = '$TERM_C7'

[colors.bright]
black   = '$TERM_C8'
red     = '$TERM_C9'
green   = '$TERM_C10'
yellow  = '$TERM_C11'
blue    = '$TERM_C12'
magenta = '$TERM_C13'
cyan    = '$TERM_C14'
white   = '$TERM_C15'
EOF

    # Ensure alacritty.toml imports active-theme.toml (add if missing)
    if [[ -f "$ALACRITTY_DIR/alacritty.toml" ]]; then
        if ! grep -q "active-theme.toml" "$ALACRITTY_DIR/alacritty.toml"; then
            # Insert active-theme.toml as first import entry
            sed -i 's|^\(import = \[\s*\)|\1\n  "~/.config/alacritty/active-theme.toml",|' \
                "$ALACRITTY_DIR/alacritty.toml"
        fi
        # Replace any existing theme import line to point to active-theme.toml
        # (removes old theme-specific imports, keeps keybinds import)
        sed -i 's|"~/.config/alacritty/[^k][^"]*\.toml"|"~/.config/alacritty/active-theme.toml"|g' \
            "$ALACRITTY_DIR/alacritty.toml"
    fi
fi



# ══════════════════════════════════════════════════════════════════════════════
# GHOSTTY — update ~/.config/ghostty/config or config.ghostty
# ══════════════════════════════════════════════════════════════════════════════
GHOSTTY_CFG="${XDG_CONFIG_HOME:-$HOME/.config}/ghostty/config"
[[ ! -f "$GHOSTTY_CFG" && -f "${XDG_CONFIG_HOME:-$HOME/.config}/ghostty/config.ghostty" ]] && GHOSTTY_CFG="${XDG_CONFIG_HOME:-$HOME/.config}/ghostty/config.ghostty"
# Ensure custom themes shipped with dwm are present
GHOSTTY_THEMES_SRC="$HOME/.local/share/dwm/ghostty/themes"
GHOSTTY_THEMES_DST="${XDG_CONFIG_HOME:-$HOME/.config}/ghostty/themes"
if [[ -d "$GHOSTTY_THEMES_SRC" ]]; then
    mkdir -p "$GHOSTTY_THEMES_DST"
    cp -r "$GHOSTTY_THEMES_SRC/"* "$GHOSTTY_THEMES_DST/" 2>/dev/null || true
fi
if [[ -n "$GHOSTTY_THEME" && -f "$GHOSTTY_CFG" ]]; then
    if grep -q "^theme[[:space:]]*=" "$GHOSTTY_CFG"; then
        sed -i "s|^theme[[:space:]]*=.*|theme = $GHOSTTY_THEME|" "$GHOSTTY_CFG"
    else
        echo "theme = $GHOSTTY_THEME" >> "$GHOSTTY_CFG"
    fi
    # Remove any manually set background/foreground so the named theme controls colors
    sed -i '/^background[[:space:]]*=[^=]/d' "$GHOSTTY_CFG"
    sed -i '/^foreground[[:space:]]*=[^=]/d' "$GHOSTTY_CFG"
fi


# ══════════════════════════════════════════════════════════════════════════════
# ROFI — update @theme line in ~/.config/rofi/config.rasi
# ══════════════════════════════════════════════════════════════════════════════
ROFI_CFG="${XDG_CONFIG_HOME:-$HOME/.config}/rofi/config.rasi"
if [[ -n "$ROFI_THEME" && -f "$ROFI_CFG" ]]; then
    if grep -q '@theme' "$ROFI_CFG"; then
        sed -i "s|@theme \".*\"|@theme \"themes/$ROFI_THEME.rasi\"|g" "$ROFI_CFG"
    else
        echo "@theme \"themes/$ROFI_THEME.rasi\"" >> "$ROFI_CFG"
    fi
fi


# ══════════════════════════════════════════════════════════════════════════════
# GTK DARK / LIGHT MODE & DYNAMIC THEME COLORS
# ══════════════════════════════════════════════════════════════════════════════
if [[ "$DARK_MODE" == "true" ]]; then
    GTK_COLOR_SCHEME="prefer-dark"
    GTK_THEME_NAME="Adwaita-dark"
    GTK_DARK_PREF=1
else
    GTK_COLOR_SCHEME="default"
    GTK_THEME_NAME="Adwaita"
    GTK_DARK_PREF=0
fi

# Determine closest GNOME accent color name (blue, teal, green, yellow, orange, red, pink, purple, slate)
GNOME_ACCENT="$(python3 -c "
import colorsys, sys

def hex_to_rgb(h):
    h = h.lstrip('#')
    return tuple(int(h[i:i+2], 16) / 255.0 for i in (0, 2, 4))

gnome_accents = {
    'blue': '#3584e4',
    'teal': '#21a499',
    'green': '#3a944a',
    'yellow': '#e5a50a',
    'orange': '#e66100',
    'red': '#e01b24',
    'pink': '#d56199',
    'purple': '#9141ac',
}

def closest(color_hex):
    try:
        r, g, b = hex_to_rgb(color_hex)
        h, s, v = colorsys.rgb_to_hsv(r, g, b)
        if s < 0.15:
            return 'slate'
        best = 'blue'
        best_diff = 999.0
        for name, code in gnome_accents.items():
            r2, g2, b2 = hex_to_rgb(code)
            h2, s2, v2 = colorsys.rgb_to_hsv(r2, g2, b2)
            diff = min(abs(h - h2), 1.0 - abs(h - h2))
            if diff < best_diff:
                best_diff = diff
                best = name
        return best
    except Exception:
        return 'blue'

print(closest(sys.argv[1]))
" "$TERM_CURSOR" 2>/dev/null || echo "blue")"

# Helper: set or add a key in a [Settings] ini file without destroying other settings
gtk_ini_set() {
    local file="$1" key="$2" value="$3"
    mkdir -p "$(dirname "$file")"
    if [[ ! -f "$file" ]]; then
        printf '[Settings]\n%s=%s\n' "$key" "$value" > "$file"
        return
    fi
    if grep -q "^${key}" "$file"; then
        sed -i "s|^${key}=.*|${key}=${value}|" "$file"
    elif grep -q '^\[Settings\]' "$file"; then
        sed -i "/^\[Settings\]/a ${key}=${value}" "$file"
    else
        printf '\n[Settings]\n%s=%s\n' "$key" "$value" >> "$file"
    fi
}

# GTK3 Settings
gtk_ini_set "${XDG_CONFIG_HOME:-$HOME/.config}/gtk-3.0/settings.ini" \
    "gtk-application-prefer-dark-theme" "$GTK_DARK_PREF"
