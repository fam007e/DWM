fi

# ── Dynamic GTK 4 / Libadwaita Colors (~/.config/gtk-4.0/gtk.css) ───────────
GTK4_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/gtk-4.0"
mkdir -p "$GTK4_DIR"
rm -f "$GTK4_DIR/gtk.css" "$GTK4_DIR/gtk-dark.css"

