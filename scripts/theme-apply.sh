    "gtk-theme-name" "$GTK_THEME_NAME"

# GTK4 Settings
gtk_ini_set "${XDG_CONFIG_HOME:-$HOME/.config}/gtk-4.0/settings.ini" \
    "gtk-application-prefer-dark-theme" "$GTK_DARK_PREF"
gtk_ini_set "${XDG_CONFIG_HOME:-$HOME/.config}/gtk-4.0/settings.ini" \
    "gtk-theme-name" "$GTK_THEME_NAME"

# GTK2 Settings
printf 'gtk-theme-name="%s"\n' "$GTK_THEME_NAME" > "$HOME/.gtkrc-2.0"

